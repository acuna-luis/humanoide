#!/usr/bin/env python3
"""Apply or restore staged uDoke SPS env files; never restart containers.

Requires externally verified backups before --install. Uses the staged,
byte-preserving candidates generated by stage_pico_v4_migration.py --env-only.
"""
import argparse
import base64
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from scripts.collect_estop_available_readonly import execute
from scripts.teleoperation.stage_pico_v4_migration import STAGE

REMOTE = r'''
import base64, hashlib, json, os, pathlib, stat, sys, tempfile
ns = {'__name__':'profile_library'}
exec(base64.b64decode(sys.argv[1]),ns)
stage = pathlib.Path(sys.argv[2])
mode = sys.argv[3]
before = [(stage/'compose.before.yml').read_bytes(), (stage/'db.before.json').read_bytes()]
candidate = [(stage/'compose.candidate.yml').read_bytes(), (stage/'db.candidate.json').read_bytes()]
if tuple(candidate) != ns['prepare'](*before):
    raise RuntimeError('Staged candidates differ from the reviewed transformation')
targets = [pathlib.Path('/home/walker/.config/udoke/walker/compose.yml'),
           pathlib.Path('/home/walker/.config/udoke/db.json')]
current = [p.read_bytes() for p in targets]
if current not in [before,candidate]:
    raise RuntimeError('Current configuration changed or is inconsistent; no writes')
desired = before if mode == 'rollback' else candidate
changed = False
if mode != 'check' and current != desired:
    staged = []
    try:
        for target, data in zip(targets,desired):
            metadata = target.stat()
            if metadata.st_uid != os.getuid():
                raise RuntimeError('Unexpected configuration owner')
            fd,name = tempfile.mkstemp(prefix='.v4-env-',dir=target.parent)
            staged.append((target,name))
            with os.fdopen(fd,'wb') as f:
                f.write(data); f.flush(); os.fsync(f.fileno())
            os.chmod(name,stat.S_IMODE(metadata.st_mode))
        if [p.read_bytes() for p in targets] != current:
            raise RuntimeError('Configuration changed before replacement')
        for target,name in staged: os.replace(name,target)
        if [p.read_bytes() for p in targets] != desired:
            raise RuntimeError('Configuration verification failed')
        changed = True
    finally:
        for _,name in staged:
            if os.path.exists(name):os.unlink(name)
print(json.dumps(dict(mode=mode,changed=changed,reloaded=False,
    state='sps' if [p.read_bytes() for p in targets] == candidate else 'clamp',
    hashes={str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in targets})))
'''


def main():
    p = argparse.ArgumentParser(description=__doc__)
    modes = p.add_mutually_exclusive_group()
    modes.add_argument('--install', action='store_true')
    modes.add_argument('--rollback', action='store_true')
    modes.add_argument('--check', action='store_true')
    p.add_argument('--evidence', type=Path, required=True)
    args = p.parse_args()
    if args.install:
        proof = json.loads((args.evidence/'migration-backups-verified.json').read_text())
        if not all(proof.get(k) is True for k in ('motion','vision','selected')):
            raise ValueError('External backup verification is incomplete')
    helper = base64.b64encode(Path(__file__).with_name('prepare_pico_v4_motion_env.py').read_bytes()).decode()
    mode = 'install' if args.install else 'rollback' if args.rollback else 'check'
    result = execute('motion',['python3','-c',REMOTE,helper,STAGE,mode])
    (args.evidence/('native-env-'+mode+'.json')).write_text(json.dumps(result,indent=2))
    print(json.dumps(result))
    return result.get('returncode',1)


if __name__ == '__main__':
    raise SystemExit(main())
